"""Convert the HSE RUZ timetable export (.xls) into admin/schedule.md.

Writes admin/schedule.md, admin/schedule.csv and book/_schedule-tables.md.
Usage: make schedule   (or pass a path: make schedule XLS=admin/raw/<file>.xls)
Without a path the newest .xls in admin/raw/ is used.
"""
import re
import sys
from pathlib import Path

import pandas as pd

DAYS = {"Пн": "Mon", "Вт": "Tue", "Ср": "Wed", "Чт": "Thu", "Пт": "Fri", "Сб": "Sat", "Вс": "Sun"}

src = Path(sys.argv[1]) if len(sys.argv) > 1 and sys.argv[1] else max(Path("admin/raw").glob("*.xls"), key=lambda f: f.stat().st_mtime)
df = pd.read_excel(src, header=0, engine="xlrd")
df = df.rename(columns={"Дата": "date", "День": "day", "Начало": "start", "Окончание": "end",
                        "Вид работ": "kind", "Аудитория": "room", "Группа": "group"})
df["date"] = pd.to_datetime(df["date"]).dt.date
df["day"] = df["day"].map(DAYS)
df["kind"] = df["kind"].map(lambda k: "Lecture" if "Лекц" in k else "Seminar")
df["group"] = df.apply(
    lambda r: "all" if r["kind"] == "Lecture" else "G" + re.search(r"_(\d)#Г#", r["group"]).group(1), axis=1)
df["room"] = df["room"].astype(str)
df = df.sort_values(["date", "start"]).reset_index(drop=True)

# Number sessions: lecture days L1.., seminar meetings per group S1..
lec_days = {d: i + 1 for i, d in enumerate(sorted(df.loc[df.kind == "Lecture", "date"].unique()))}
df["session"] = ""
df.loc[df.kind == "Lecture", "session"] = df.loc[df.kind == "Lecture", "date"].map(lambda d: f"L{lec_days[d]}")
for g, idx in df[df.kind == "Seminar"].groupby("group").groups.items():
    for n, i in enumerate(idx, 1):
        df.at[i, "session"] = f"S{n}"

lines = [
    "# Teaching schedule, module 2 (Nov–Dec 2026)",
    "",
    f"Generated by `scripts/schedule_from_xls.py` from `{src.as_posix()}`. Do not edit by hand; re-run the script.",
    "",
    "- Course (RUZ): Теория вероятностей и математическая статистика (анг) = Probability Theory and Mathematical Statistics",
    "- Programme: Б 38.03.02 ВШБ, Международный бизнес (International Business), Higher School of Business",
    "- Building: Shabolovka ul. 26-28 (all sessions). Slots are 80 min.",
    "- Seminar groups: G1, G2, G3 (RUZ codes 26_27_М_ТВИМС_Г_1258330_1/2/3). Lectures are for the whole stream.",
    "- Module 3 (Jan–Mar 2027) is not in this export yet.",
    "",
    "## All sessions",
    "",
    "| Date | Day | Time | Type | Group | Session | Room |",
    "|---|---|---|---|---|---|---|",
]
for r in df.itertuples():
    lines.append(f"| {r.date} | {r.day} | {r.start}–{r.end} | {r.kind} | {r.group} | {r.session} | {r.room} |")

lines += ["", "## Seminar grid (date, time, room per group)", "", "| Seminar | G1 | G2 | G3 |", "|---|---|---|---|"]
sem = df[df.kind == "Seminar"]
for n in sorted(sem["session"].unique(), key=lambda s: int(s[1:])):
    cells = []
    for g in ["G1", "G2", "G3"]:
        r = sem[(sem.group == g) & (sem.session == n)].iloc[0]
        cells.append(f"{r.date:%d %b} {r.day} {r.start}, {r.room}")
    lines.append(f"| {n} | " + " | ".join(cells) + " |")

lines += ["", "## Summary", ""]
lines.append(f"- Lectures: {len(lec_days)} days, {int((df.kind == 'Lecture').sum())} slots.")
for g in ["G1", "G2", "G3"]:
    sub = df[df.group == g]
    lines.append(f"- {g}: {len(sub)} seminar slots, " + ", ".join(f"{d:%d %b}" for d in sub["date"]))
doubles = df[df.kind == "Seminar"].groupby(["date", "group"]).size()
doubles = doubles[doubles > 1]
if len(doubles):
    lines.append("- Double seminar slots (same group, same day): "
                 + "; ".join(f"{g} on {d:%d %b}" for (d, g) in doubles.index))

# Student-facing tables for the book appendix (book/schedule.qmd includes this file)
book = ["## Lectures", "", "| Lecture | Date | Time | Room |", "|---|---|---|---|"]
for (sess, d), grp in df[df.kind == "Lecture"].groupby(["session", "date"], sort=False):
    times = ", ".join(f"{r.start}–{r.end}" for r in grp.itertuples())
    book.append(f"| {sess[1:]} | {grp.iloc[0].day} {d:%d %b} | {times} | {', '.join(dict.fromkeys(grp.room))} |")
book += ["", "## Seminars", ""] + lines[lines.index("| Seminar | G1 | G2 | G3 |"):lines.index("## Summary") - 1]
Path("book/_schedule-tables.md").write_text("\n".join(book) + "\n", encoding="utf-8")

out = Path("admin/schedule.md")
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
df[["date", "day", "start", "end", "kind", "group", "session", "room"]].to_csv("admin/schedule.csv", index=False)
print(out.read_text())
